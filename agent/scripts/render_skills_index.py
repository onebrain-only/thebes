#!/usr/bin/env python3
"""Render agent/skills/AVAILABLE.md from the skill folders.

The index is generated, never written by hand: one row per folder under
agent/skills/ that holds a SKILL.md, with the description from its frontmatter.

    python3 agent/scripts/render_skills_index.py           # write the file
    python3 agent/scripts/render_skills_index.py --check   # exit 1 if it is stale
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKILLS = ROOT / "agent" / "skills"
INDEX = SKILLS / "AVAILABLE.md"
WIDTH = 150

HEADER = """# Skills available in this repository

Generated by `python3 agent/scripts/render_skills_index.py`. Do not edit by hand: change a
skill's own `SKILL.md` and render again.

## Project skills: `agent/skills/` ({count})

`.claude/skills` is a link to this folder, so every session whose working directory is this
repository sees them. Invoke one with the Skill tool by name. A code brief names `tdd`,
`rtl-arabic-checklist` and `drive-the-app`; Edfu (QA) also uses `task-review`.

`grilling` and `writing-for-agents` are kept here as the source. `grill-me` is the shortcut
that calls `grilling`.

| Skill | What it is for |
|---|---|
"""

FOOTER = """
## Plugins

One plugin is enabled in `.claude/settings.json`: `dart-flutter@dart-flutter`. It is installed
per machine, not from this repository; its skills appear as `dart-flutter:<name>`. No other
plugin is enabled, and a role file that names a skill not listed above names one that does not
exist here.

## Part of the QA toolchain, not skills

- Playwright (`@playwright/test`) with Chromium, at the `Dabbler/dabbler-code` root: `npm run test:e2e`.
- `dart mcp-server`, started by the dart-flutter plugin as `dart-mcp-server`.
"""


def description(skill_md: Path) -> str:
    lines = skill_md.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return ""
    block = []
    for line in lines[1:]:
        if line.strip() == "---":
            break
        block.append(line)
    for i, line in enumerate(block):
        if not line.startswith("description:"):
            continue
        value = line[len("description:"):].strip()
        if value in (">", ">-", "|", "|-", ""):
            folded = []
            for cont in block[i + 1:]:
                if cont and not cont[0].isspace():
                    break
                folded.append(cont.strip())
            value = " ".join(part for part in folded if part)
        return value.strip().strip('"').strip("'")
    return ""


def render() -> str:
    rows = []
    for folder in sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").is_file()):
        text = " ".join(description(folder / "SKILL.md").split()).replace("|", "\\|")
        if len(text) > WIDTH:
            text = text[: WIDTH - 1].rstrip() + "…"
        rows.append(f"| `{folder.name}` | {text} |")
    return HEADER.format(count=len(rows)) + "\n".join(rows) + "\n" + FOOTER


def main(argv: list[str]) -> int:
    wanted = render()
    if "--check" in argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != wanted:
            print("stale: agent/skills/AVAILABLE.md (run render_skills_index.py)")
            return 1
        print("ok: agent/skills/AVAILABLE.md")
        return 0
    INDEX.write_text(wanted, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
